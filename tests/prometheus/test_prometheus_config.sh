# Conventions test for the repo-managed Prometheus config.
#
# promtool (run separately in CI) proves the files PARSE. This covers the things
# it cannot, and specifically pins the three regressions this repo actually
# suffered so they cannot come back:
#
#   1. a scrape target of localhost:9100, which inside the container resolves to
#      Prometheus itself and can therefore never be up;
#   2. a listener published on 0.0.0.0 with --web.enable-lifecycle and no auth;
#   3. prometheus.yml generated by a shell heredoc into a host path nothing
#      mounts, so hand-fixes were silently discarded.
#
# It also enforces that every alert is DELIVERABLE: scripts/tt-prometheus-alerts.sh
# mails the severity and the summary, so an alert without them produces an
# unactionable message.
#
# Usage: bash tests/prometheus/test_prometheus_config.sh
# Exit:  0 all checks pass, 1 at least one failure

set -uo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
CFG_DIR="${REPO_ROOT}/infra/docker/prometheus"
COMPOSE="${REPO_ROOT}/infra/docker/prometheus-dev1.yml"
NGINX="${REPO_ROOT}/infra/nginx/sites-available/prometheus.conf"
OLD_DEPLOY="${REPO_ROOT}/scripts/deploy-prometheus-tensorflow.sh"

pass=0
fail=0

ok()   { pass=$((pass + 1)); printf '  ok   %s\n' "$1"; }
bad()  { fail=$((fail + 1)); printf '  FAIL %s\n' "$1"; }
check(){ if eval "$2"; then ok "$1"; else bad "$1"; fi; }

printf '\n== files present ==\n'
check "prometheus.yml exists"        "[ -f '${CFG_DIR}/prometheus.yml' ]"
check "at least one rule file"       "compgen -G '${CFG_DIR}/rules/*.yml' >/dev/null"
check "node-exporter compose exists" "[ -f '${REPO_ROOT}/infra/docker/node-exporter-dev1.yml' ]"

printf '\n== scrape targets ==\n'
# The original bug. A node-exporter target must be the container name.
# Only target lines count: the config's comments mention localhost:9100 to
# explain why it was wrong, and that history is worth keeping.
check "no localhost:9100 target" \
    "! grep -Eq 'targets:.*localhost:9100' '${CFG_DIR}/prometheus.yml'"
check "node job targets node-exporter:9100" \
    "grep -Eq '\"node-exporter:9100\"' '${CFG_DIR}/prometheus.yml'"
check "docker job targets the docker0 gateway" \
    "grep -Eq '172\.17\.0\.1:9323' '${CFG_DIR}/prometheus.yml'"
check "rule_files is declared" \
    "grep -Eq '^rule_files:' '${CFG_DIR}/prometheus.yml'"
check "rule_files points inside the container mount" \
    "grep -Eq '/etc/prometheus/rules' '${CFG_DIR}/prometheus.yml'"

printf '\n== every alert is deliverable ==\n'
# awk walks the rule files and, at each alert boundary, asserts the previous
# alert had an expr, a severity label and a summary annotation.
rule_report="$(awk '
    function close_alert() {
        if (!in_alert) return
        if (!has_expr)  { printf "%s: alert %s has no expr\n", FILENAME, name;   bad=1 }
        if (!has_sev)   { printf "%s: alert %s has no severity\n", FILENAME, name; bad=1 }
        if (!has_sum)   { printf "%s: alert %s has no summary annotation\n", FILENAME, name; bad=1 }
    }
    /^[[:space:]]*-[[:space:]]*alert:[[:space:]]*/ {
        close_alert()
        in_alert = 1
        name = $0; sub(/.*alert:[[:space:]]*/, "", name); gsub(/[" ]/, "", name)
        has_expr = 0; has_sev = 0; has_sum = 0
        next
    }
    in_alert && /^[[:space:]]*expr:/    { has_expr = 1 }
    in_alert && /^[[:space:]]*severity:/ { has_sev = 1 }
    in_alert && /^[[:space:]]*summary:/  { has_sum = 1 }
    END { close_alert(); exit bad }
' "${CFG_DIR}"/rules/*.yml 2>&1)"
if [ -z "$rule_report" ]; then
    ok "all alerts have expr, severity and summary"
else
    bad "alert completeness"
    printf '%s\n' "$rule_report" | sed 's/^/       /'
fi

printf '\n== exposure ==\n'
check "prometheus listener is loopback-only" \
    "grep -Eq '\"127\.0\.0\.1:3720:9090\"' '${COMPOSE}'"
check "listener is not on 0.0.0.0" \
    "! grep -Eq '0\.0\.0\.0:3720:9090' '${COMPOSE}'"
check "retention is size-capped" \
    "grep -Eq 'storage\.tsdb\.retention\.size' '${COMPOSE}'"
check "vhost requires auth_basic" \
    "grep -Eq 'auth_basic[[:space:]]+\"' '${NGINX}'"
check "vhost is gate-ready" \
    "grep -Eq 'tt-gate\.conf' '${NGINX}'"
check "vhost proxies to IPv4 loopback" \
    "grep -Eq 'proxy_pass http://127\.0\.0\.1:3720' '${NGINX}'"

printf '\n== config is repo-owned, not generated ==\n'
check "old deploy script no longer writes prometheus.yml" \
    "! grep -Eq 'prometheus/config/prometheus\.yml' '${OLD_DEPLOY}'"
check "old deploy script no heredoc config" \
    "! grep -Eq 'PROMETHEUS_EXTRA_SETUP' '${OLD_DEPLOY}'"
check "compose mounts the repo config dir read-only" \
    "grep -Eq 'infra/docker/prometheus:/etc/prometheus:ro' '${COMPOSE}'"

printf '\n%d passed, %d failed\n\n' "$pass" "$fail"
[ "$fail" -eq 0 ]
